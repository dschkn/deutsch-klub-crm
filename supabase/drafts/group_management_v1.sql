create table public.crm_groups (
  id uuid primary key default gen_random_uuid(),
  group_number bigint generated always as identity unique,
  name text not null,
  language text not null check (language in ('German', 'English')),
  level text not null,
  course_type text not null,
  teacher_id text,
  teacher_name text not null default '',
  textbook text not null default '',
  academic_hours integer not null default 0 check (academic_hours >= 0),
  price numeric(12, 2) not null default 0 check (price >= 0),
  max_students integer not null default 12 check (max_students > 0),
  start_date date not null,
  end_date date,
  status public.crm_group_status not null default 'planned',
  internal_note text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date is null or end_date >= start_date)
);

