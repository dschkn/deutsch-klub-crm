create or replace function public.crm_set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'crm_groups', 'crm_students', 'crm_group_memberships', 'crm_group_schedule_rules',
    'crm_lessons', 'crm_task_templates', 'crm_tasks', 'crm_comments'
  ] loop
    execute format('create trigger %I before update on public.%I for each row execute function public.crm_set_updated_at()', table_name || '_set_updated_at', table_name);
  end loop;
end $$;

-- Authenticated CRM staff must receive crm_role in app_metadata through an
-- administrator-controlled Auth operation. Never derive authorization from user_metadata.
create or replace function public.crm_is_staff()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce((select auth.jwt() -> 'app_metadata' ->> 'crm_role'), '')
    in ('administrator', 'senior_administrator', 'director');
$$;

revoke all on function public.crm_is_staff() from public, anon;
grant execute on function public.crm_is_staff() to authenticated, service_role;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'crm_groups', 'crm_students', 'crm_group_memberships', 'crm_group_schedule_rules',
    'crm_lessons', 'crm_task_templates', 'crm_tasks', 'crm_comments', 'crm_student_files'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon', table_name);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', table_name);
    execute format('create policy %I on public.%I for select to authenticated using ((select public.crm_is_staff()))', table_name || '_staff_select', table_name);
    execute format('create policy %I on public.%I for insert to authenticated with check ((select public.crm_is_staff()))', table_name || '_staff_insert', table_name);
    execute format('create policy %I on public.%I for update to authenticated using ((select public.crm_is_staff())) with check ((select public.crm_is_staff()))', table_name || '_staff_update', table_name);
    execute format('create policy %I on public.%I for delete to authenticated using ((select public.crm_is_staff()))', table_name || '_staff_delete', table_name);
  end loop;
end $$;

grant usage, select on all sequences in schema public to authenticated;

